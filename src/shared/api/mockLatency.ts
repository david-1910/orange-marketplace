/**
 * Имитация сетевой задержки, чтобы состояния загрузки были видны.
 *
 * Лежит в shared, а не в слайсе сущности: задержку ждут запросы
 * и товаров, и категорий, а дублировать таймер в каждом api-сегменте
 * значит потом менять его в нескольких местах. Домена здесь нет —
 * это чистая инфраструктура моков.
 */
const MOCK_LATENCY = 350;

export const mockLatency = (): Promise<void> =>
  new Promise<void>((resolve) => window.setTimeout(resolve, MOCK_LATENCY));
