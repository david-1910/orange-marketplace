import { useState } from 'react';

interface BumpState {
  /** Значение, под которое посчитан ключ. */
  value: number;
  key: number;
}

/**
 * Ключ, который меняется каждый раз, когда наблюдаемое число выросло.
 *
 * Нужен, чтобы перезапускать анимацию у элемента со счётчиком: motion
 * проигрывает `initial → animate` заново, когда меняется `key`,
 * поэтому пульс срабатывает на каждое добавление, а не один раз при
 * монтировании.
 *
 * Сравнение с прошлым значением сделано через состояние с
 * корректировкой во время рендера, а не через useRef: читать и писать
 * ref в теле компонента нельзя — правило react-hooks/refs справедливо
 * это запрещает, потому что ref не участвует в рендере и React не
 * обязан перерисовать компонент после его изменения. useEffect тоже не
 * подходит: он дал бы лишний проход и анимацию на кадр позже события.
 *
 * Реагирует только на рост: убрали товар из корзины — счётчик
 * уменьшился, и подпрыгивать в ответ на удаление незачем.
 */
export const useBumpOnChange = (value: number): number => {
  const [state, setState] = useState<BumpState>({ value, key: 0 });

  if (state.value !== value) {
    setState((current) => ({
      value,
      key: value > current.value ? current.key + 1 : current.key,
    }));
  }

  return state.key;
};
