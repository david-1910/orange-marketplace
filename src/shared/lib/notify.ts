import { toast } from 'sonner';

/**
 * Уведомления о событиях.
 *
 * Тонкая обёртка над sonner, а не прямые вызовы toast по слайсам:
 * тогда настройки (длительность, тексты кнопки отмены, поведение при
 * prefers-reduced-motion) задаются один раз, а замена библиотеки не
 * потребует правок в десяти фичах.
 *
 * Лежит в shared/lib, потому что домена не знает: принимает готовый
 * текст. Что именно сообщать — решает фича, где произошло событие.
 */
export const notify = {
  /** Нейтральное событие: «добавлено», «убрано». */
  info: (message: string) => toast(message),

  success: (message: string) => toast.success(message),

  error: (message: string) => toast.error(message),

  /**
   * Событие с возможностью отменить.
   *
   * Отмена нужна необратимым на вид действиям — удалению из корзины
   * или очистке при выходе: человек нажимает крестик случайно чаще,
   * чем кажется, а восстановить состав корзины руками долго.
   */
  undo: (message: string, onUndo: () => void) =>
    toast(message, {
      action: { label: 'Вернуть', onClick: onUndo },
    }),
};
