export interface Product {
  id: string;
  title: string;
  categoryId: string;
  /** Цена в сумах, целое число. Дробей в сумах не бывает. */
  price: number;
  /** Цена до скидки; отсутствует, если скидки нет. */
  oldPrice?: number;
  emoji: string;
  /**
   * Идентификатор фото на Unsplash (открытая лицензия).
   * Храним id, а не готовый URL: размер запрашивается под место
   * вывода, поэтому карточка не тянет фото для страницы товара.
   */
  photoId: string;
  /** Дополнительные фото для галереи на странице товара. */
  galleryPhotoIds?: string[];
  inStock: boolean;
  /** Оценка 0…5 с шагом 0.1. */
  rating: number;
  reviewsCount: number;
}

/**
 * Порядок выдачи товаров.
 *
 * Значение приходит в запрос, а не применяется к загруженной
 * странице: при постраничной выдаче клиент видит только часть
 * товаров, и сортировка на клиенте перемешала бы порядок внутри
 * страницы, оставив дорогие товары на второй.
 */
export type ProductSort = 'price-asc' | 'price-desc' | 'rating-desc';

export interface ProductFilters {
  categoryId?: string;
  /**
   * Выборка по конкретным идентификаторам — так страница избранного
   * получает свои товары. Порядок ответа повторяет порядок ids,
   * поэтому список сохраняет тот вид, в котором его собрал
   * пользователь.
   */
  ids?: string[];
  /** Нижняя граница цены включительно. */
  minPrice?: number;
  /** Верхняя граница цены включительно. */
  maxPrice?: number;
  /** Минимальный рейтинг включительно: 4 означает «4.0 и выше». */
  minRating?: number;
  /**
   * Поисковый запрос. Сопоставляется с названием товара по вхождению,
   * без учёта регистра.
   */
  query?: string;
  /** Порядок выдачи. Без него — порядок каталога. */
  sort?: ProductSort;
  /** Сколько товаров вернуть. Без лимита — все. */
  limit?: number;
}

/**
 * Границы цен по всему каталогу — для слайдера диапазона.
 *
 * Приходят из источника, а не считаются в компоненте: клиент видит
 * только загруженные страницы и о самом дешёвом и самом дорогом
 * товаре каталога знать не может.
 */
export interface PriceRange {
  min: number;
  max: number;
}

/**
 * Одна страница каталога.
 *
 * `nextPage` считает источник, а не клиент: иначе `getNextPageParam`
 * пришлось бы угадывать конец списка по длине массива, а при неполной
 * последней странице это ломается. Настоящий API отдал бы ровно такой
 * же ответ.
 */
export interface ProductPage {
  items: Product[];
  /** null — страниц больше нет. */
  nextPage: number | null;
  /** Всего товаров по этому фильтру — для счётчика «показано N из M». */
  total: number;
}
